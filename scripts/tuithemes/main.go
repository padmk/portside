package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"regexp"
	"strconv"
	"strings"
)

const output = "internal/tui/theme/palettes_gen.go"

var declarations = regexp.MustCompile(`(?m)(--[\w-]+)\s*:\s*([^;]+);`)
var blocks = regexp.MustCompile(`(?s)([^{}]+)\{([^{}]*)\}`)
var comments = regexp.MustCompile(`(?s)/\*.*?\*/`)
var families = regexp.MustCompile(`\{\s*id:\s*'([^']+)',\s*label:\s*'([^']+)',\s*dark:\s*'([^']+)',\s*light:\s*'([^']+)'\s*\}`)
var reference = regexp.MustCompile(`^var\((--[\w-]+)\)$`)
var mix = regexp.MustCompile(`^color-mix\(in srgb,\s*(.+)\s+([0-9]+(?:\.[0-9]+)?)%,\s*(.+)\)$`)

type rgb [3]float64

func read(path string) string {
	b, e := os.ReadFile(path)
	if e != nil {
		panic(e)
	}
	return string(b)
}
func tokens(s string) map[string]string {
	m := map[string]string{}
	for _, v := range declarations.FindAllStringSubmatch(s, -1) {
		m[v[1]] = strings.TrimSpace(v[2])
	}
	return m
}
func resolve(name string, m map[string]string, seen map[string]bool) rgb {
	if seen[name] {
		panic("cyclic token: " + name)
	}
	v, ok := m[name]
	if !ok {
		panic("missing token: " + name)
	}
	seen[name] = true
	c := parse(v, m, seen)
	delete(seen, name)
	return c
}
func parse(v string, m map[string]string, seen map[string]bool) rgb {
	v = strings.TrimSpace(v)
	if r := reference.FindStringSubmatch(v); r != nil {
		return resolve(r[1], m, seen)
	}
	if v == "transparent" {
		return resolve("--bg", m, seen)
	}
	if r := mix.FindStringSubmatch(v); r != nil {
		p, e := strconv.ParseFloat(r[2], 64)
		if e != nil || p < 0 || p > 100 {
			panic("invalid mix: " + v)
		}
		a, b := parse(r[1], m, seen), parse(r[3], m, seen)
		var c rgb
		for i := range c {
			c[i] = (a[i]*p + b[i]*(100-p)) / 100
		}
		return c
	}
	if strings.HasPrefix(v, "#") {
		h := v[1:]
		if len(h) == 3 {
			h = string([]byte{h[0], h[0], h[1], h[1], h[2], h[2]})
		}
		if len(h) != 6 && len(h) != 8 {
			panic("invalid hex: " + v)
		}
		n, e := strconv.ParseUint(h, 16, 32)
		if e != nil {
			panic(e)
		}
		alpha := 1.0
		if len(h) == 8 {
			alpha = float64(n&255) / 255
			n >>= 8
		}
		c := rgb{float64(n >> 16), float64(n >> 8 & 255), float64(n & 255)}
		if alpha < 1 {
			bg := resolve("--bg", m, seen)
			for i := range c {
				c[i] = c[i]*alpha + bg[i]*(1-alpha)
			}
		}
		return c
	}
	panic("unsupported color: " + v)
}
func color(name string, m map[string]string) string {
	return hex(resolve(name, m, map[string]bool{}))
}
func hex(c rgb) string {
	return fmt.Sprintf("#%02x%02x%02x", int(math.Round(c[0])), int(math.Round(c[1])), int(math.Round(c[2])))
}

// luminance is the WCAG relative luminance of c.
func luminance(c rgb) float64 {
	var l [3]float64
	for i, v := range c {
		x := math.Round(v) / 255
		if x <= 0.03928 {
			l[i] = x / 12.92
		} else {
			l[i] = math.Pow((x+0.055)/1.055, 2.4)
		}
	}
	return 0.2126*l[0] + 0.7152*l[1] + 0.0722*l[2]
}
func contrast(a, b rgb) float64 {
	x, y := luminance(a), luminance(b)
	return (math.Max(x, y) + 0.05) / (math.Min(x, y) + 0.05)
}

// readable is fg mixed toward text in 1% steps until it reads at 4.5:1 on
// every background, the way semantic.css derives its text twins of colors.
func readable(fg, text rgb, bgs ...rgb) rgb {
	for p := 100; p >= 0; p-- {
		var c rgb
		for i := range c {
			c[i] = (fg[i]*float64(p) + text[i]*float64(100-p)) / 100
		}
		ok := true
		for _, bg := range bgs {
			if contrast(c, bg) < 4.5 {
				ok = false
			}
		}
		if ok {
			return c
		}
	}
	return text
}
// maxTint is the most of Accent the selected row's background takes.
const maxTint = 30

// selection is the selected row's background: Accent tinted into Surface
// as strongly as up to maxTint percent while what a row draws on it stays
// readable: text at 4.5:1, and labels, ports and states at 3:1.
func selection(accent, surface rgb, text, others []rgb) rgb {
	for p := maxTint; p > 0; p-- {
		var c rgb
		for i := range c {
			c[i] = (accent[i]*float64(p) + surface[i]*float64(100-p)) / 100
		}
		ok := true
		for _, fg := range text {
			ok = ok && contrast(fg, c) >= 4.5
		}
		for _, fg := range others {
			ok = ok && contrast(fg, c) >= 3
		}
		if ok {
			return c
		}
	}
	return surface
}

func render() []byte {
	registry := read("web/src/theme/registry.ts")
	fs := families.FindAllStringSubmatch(registry, -1)
	if len(fs) == 0 {
		panic("no theme families found")
	}
	semantic := comments.ReplaceAllString(read("web/src/styles/semantic.css"), "")
	shared := map[string]string{}
	themes := map[string]map[string]string{}
	for _, b := range blocks.FindAllStringSubmatch(semantic, -1) {
		selector := strings.TrimSpace(b[1])
		if selector == "html" || selector == ":root" {
			for k, v := range tokens(b[2]) {
				shared[k] = v
			}
		}
		re := regexp.MustCompile(`^html\[data-theme=['"]([^'"]+)['"]\]$`)
		if x := re.FindStringSubmatch(selector); x != nil {
			themes[x[1]] = tokens(b[2])
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by scripts/tuithemes; DO NOT EDIT.\npackage theme\nimport \"charm.land/lipgloss/v2\"\nvar generatedFamilies = []Family{\n")
	fields := [][2]string{{"Bg", "--bg"}, {"Surface", "--surface"}, {"Raised", "--selected"}, {"Selected", "--tui-selected"}, {"Text", "--text"}, {"Text2", "--text-2"}, {"Muted", "--text-3"}, {"Border", "--border"}, {"Accent", "--primary"}, {"AccentText", "--tui-accent-text"}, {"AccentFg", "--primary-fg"}, {"Running", "--running"}, {"Starting", "--starting"}, {"Crashed", "--crashed"}, {"External", "--external"}, {"Stopped", "--stopped"}, {"Warn", "--warn"}, {"Info", "--info"}, {"Port", "--tui-port"}}
	for _, f := range fs {
		fmt.Fprintf(&out, "{ID:%q, Label:%q,", f[1], f[2])
		for i, id := range f[3:5] {
			css := read("web/src/styles/themes/" + id + ".css")
			base := tokens(comments.ReplaceAllString(css, ""))
			m := map[string]string{}
			for k, v := range base {
				m[k] = v
			}
			for k, v := range shared {
				m[k] = v
			}
			override, ok := themes[id]
			if !ok {
				panic("missing semantic theme: " + id)
			}
			for k, v := range override {
				m[k] = v
			}
			// Ports get a hue of their own between External and Running, so the
			// port column never reads as a state.
			m["--tui-port"] = "color-mix(in srgb, var(--external) 55%, var(--running))"
			fallback := map[string]string{"--text-3": "--muted", "--primary": "--accent", "--warn": "--starting", "--info": "--external"}
			if _, ok := m["--warn"]; !ok {
				if _, ok := m["--warning"]; ok {
					fallback["--warn"] = "--warning"
				}
			}
			fmt.Fprintf(&out, "%s: Palette{ID:%q, Dark:%t,", []string{"Dark", "Light"}[i], id, regexp.MustCompile(`color-scheme\s*:\s*dark\s*;`).MatchString(css))
			at := func(k string) rgb {
				if _, ok := m[k]; !ok {
					k = fallback[k]
				}
				return resolve(k, m, map[string]bool{})
			}
			var states []rgb
			for _, k := range []string{"--text-3", "--tui-port", "--running", "--starting", "--crashed", "--external", "--stopped", "--warn", "--info"} {
				states = append(states, at(k))
			}
			selected := selection(at("--primary"), at("--surface"), []rgb{at("--text"), at("--text-2")}, states)
			for _, field := range fields {
				key := field[1]
				switch key {
				case "--tui-selected":
					fmt.Fprintf(&out, "%s:lipgloss.Color(%q),", field[0], hex(selected))
					continue
				case "--tui-accent-text":
					// Accent as text: --primary, darkened toward --text until it
					// reads at 4.5:1 where the terminal UI draws it.
					c := readable(at("--primary"), at("--text"), at("--bg"), at("--surface"), at("--selected"), selected)
					fmt.Fprintf(&out, "%s:lipgloss.Color(%q),", field[0], hex(c))
					continue
				}
				if _, ok := m[key]; !ok {
					key = fallback[key]
				}
				fmt.Fprintf(&out, "%s:lipgloss.Color(%q),", field[0], color(key, m))
			}
			out.WriteString("},")
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n")
	b, e := format.Source([]byte(out.String()))
	if e != nil {
		panic(e)
	}
	return b
}
func main() {
	check := flag.Bool("check", false, "check generated palettes")
	flag.Parse()
	b := render()
	if *check {
		old, e := os.ReadFile(output)
		if e != nil || !bytes.Equal(old, b) {
			fmt.Fprintln(os.Stderr, "tuithemes: generated palettes differ; run go run ./scripts/tuithemes")
			os.Exit(1)
		}
		return
	}
	if e := os.WriteFile(output, b, 0644); e != nil {
		panic(e)
	}
}
