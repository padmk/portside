// themeEntries credits the upstream themes and fails when a theme file in the
// dashboard has no attribution here.
func themeEntries() ([]entry, error) {
	known := map[string]bool{}
	for _, f := range ownThemes {
		known[f] = true
	}
	var out []entry
	for _, t := range themes {
		for _, f := range t.files {
			known[f] = true
		}
		out = append(out, entry{
			name:    t.name,
			license: "MIT",
			source:  t.source,
			files:   []licenseFile{{"LICENSE", "MIT License\n\n" + t.copyright + "\n\n" + mitBody}},
		})
	}
	files, err := filepath.Glob("web/src/styles/themes/*.css")
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, errors.New("no theme files in web/src/styles/themes")
	}
	for _, f := range files {
		if id := strings.TrimSuffix(filepath.Base(f), ".css"); !known[id] {
			return nil, fmt.Errorf("theme %s has no attribution; add it to themes in scripts/notices", id)
		}
	}
	return out, nil
}
