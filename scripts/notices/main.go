// Command notices writes THIRD_PARTY_NOTICES.txt: the license of every Go
// module linked into ./cmd/portside, every npm package bundled into the
// dashboard (production dependencies reachable from web/package.json), and the
// color themes the dashboard palettes derive from.
//
//	go run ./scripts/notices          # rewrite the file
//	go run ./scripts/notices -check   # fail when the committed file is stale
//
// Run it from the repository root after `pnpm --dir web install`. It reads
// license files from the Go module cache and web/node_modules, and fails on a
// dependency without a license file or with a license it does not recognize,
// so a new dependency gets reviewed before it ships.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/padmk/portside/internal/app"
)

const outFile = "THIRD_PARTY_NOTICES.txt"

// platforms are the release targets; the linked module set is their union.
var platforms = [][2]string{{"darwin", "arm64"}, {"linux", "amd64"}, {"linux", "arm64"}}

type entry struct {
	name, version, license, source string
	files                          []licenseFile
}

type licenseFile struct{ name, text string }

func main() {
	check := flag.Bool("check", false, "compare with the committed file instead of writing it")
	flag.Parse()
	out, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		cur, err := os.ReadFile(outFile)
		if err != nil || !bytes.Equal(cur, out) {
			fmt.Fprintf(os.Stderr, "notices: %s is stale; run `make notices` and commit the result\n", outFile)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(outFile, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func render() ([]byte, error) {
	goMods, err := goModules()
	if err != nil {
		return nil, err
	}
	npm, err := npmPackages()
	if err != nil {
		return nil, err
	}
	themes, err := themeEntries()
	if err != nil {
		return nil, err
	}
	sections := []struct {
		title, intro string
		entries      []entry
	}{
		{"Go modules", "Compiled into the " + app.ID + " binary.", goMods},
		{"Dashboard packages", "Bundled into the dashboard embedded in the " + app.ID + " binary, including the Geist fonts.", npm},
		{"Color themes", "Dashboard and terminal palettes derived from these themes (the Neutral palette is " + app.Name + "'s own).", themes},
	}

	var b strings.Builder
	rule := strings.Repeat("=", 78)
	fmt.Fprintf(&b, "THIRD-PARTY NOTICES\n\n%s includes the third-party software listed below, each under its own license.\n", app.Name)
	b.WriteString("This file is generated by `make notices` (scripts/notices); do not edit it by hand.\n\n")
	for _, s := range sections {
		fmt.Fprintf(&b, "%s\n", s.title)
		for _, e := range s.entries {
			fmt.Fprintf(&b, "  %s (%s)\n", label(e), e.license)
		}
		b.WriteString("\n")
	}
	for _, s := range sections {
		fmt.Fprintf(&b, "%s\n%s\n%s\n\n", rule, strings.ToUpper(s.title), s.intro)
		for _, e := range s.entries {
			fmt.Fprintf(&b, "%s\n%s\nLicense: %s\n", strings.Repeat("-", 78), label(e), e.license)
			if e.source != "" {
				fmt.Fprintf(&b, "Source: %s\n", e.source)
			}
			for _, f := range e.files {
				if len(e.files) > 1 {
					fmt.Fprintf(&b, "\n%s:\n", f.name)
				}
				fmt.Fprintf(&b, "\n%s\n", f.text)
			}
			b.WriteString("\n")
		}
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func label(e entry) string {
	if e.version == "" {
		return e.name
	}
	return e.name + " " + e.version
}

// goModules lists the modules linked into ./cmd/portside on every release
// platform, plus the Go standard library and runtime.
func goModules() ([]entry, error) {
	type mod struct {
		Path, Version, Dir string
		Replace            *mod
	}
	found := map[string]mod{}
	for _, p := range platforms {
		cmd := exec.Command("go", "list", "-deps", "-json=Module", "./cmd/portside")
		cmd.Env = append(os.Environ(), "GOOS="+p[0], "GOARCH="+p[1], "CGO_ENABLED=0")
		cmd.Stderr = os.Stderr
		raw, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s/%s: %w", p[0], p[1], err)
		}
		dec := json.NewDecoder(bytes.NewReader(raw))
		for {
			var pkg struct{ Module *mod }
			if err := dec.Decode(&pkg); err != nil {
				if errors.Is(err, io.EOF) {
					break
				}
				return nil, fmt.Errorf("go list output: %w", err)
			}
			m := pkg.Module
			if m == nil || m.Version == "" && m.Replace == nil { // standard library or the main module
				continue
			}
			if m.Replace != nil {
				m = &mod{Path: m.Path, Version: m.Replace.Version, Dir: m.Replace.Dir}
			}
			found[m.Path] = *m
		}
	}

	var out []entry
	for _, m := range found {
		if m.Dir == "" {
			return nil, fmt.Errorf("%s %s is not in the module cache; run `go mod download`", m.Path, m.Version)
		}
		e, err := licensed(m.Path, m.Version, "", "https://"+m.Path, m.Dir)
		if err != nil {
			return nil, err
		}
		out = append(out, e)
	}
	slices.SortFunc(out, func(a, b entry) int { return strings.Compare(a.name, b.name) })

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return nil, fmt.Errorf("go env GOROOT: %w", err)
	}
	// Homebrew keeps the toolchain's LICENSE next to GOROOT (libexec) rather than in it.
	dir := strings.TrimSpace(string(goroot))
	std := entry{name: "Go standard library and runtime", license: "BSD-3-Clause", source: "https://go.dev"}
	for _, name := range []string{"LICENSE", "PATENTS"} {
		raw, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			raw, err = os.ReadFile(filepath.Join(filepath.Dir(dir), name))
		}
		if err != nil {
			return nil, fmt.Errorf("go toolchain %s not found in or next to %s", name, dir)
		}
		std.files = append(std.files, licenseFile{name, clean(string(raw))})
	}
	return append([]entry{std}, out...), nil
}

// npmPackages walks the production dependencies of web/package.json through
// pnpm's node_modules, resolving each package the way Node does.
func npmPackages() ([]entry, error) {
	type pkgJSON struct {
		Name, Version        string
		License              json.RawMessage
		Repository           json.RawMessage
		Dependencies         map[string]string
		OptionalDependencies map[string]string
	}
	read := func(dir string) (pkgJSON, error) {
		var p pkgJSON
		raw, err := os.ReadFile(filepath.Join(dir, "package.json"))
		if err == nil {
			err = json.Unmarshal(raw, &p)
		}
		return p, err
	}
	root, err := filepath.Abs("web")
	if err != nil {
		return nil, err
	}
	if _, err := os.Stat(filepath.Join(root, "node_modules")); err != nil {
		return nil, errors.New("web/node_modules is missing; run `pnpm --dir web install --frozen-lockfile`")
	}
	resolve := func(from, name string) (string, bool) {
		for dir := from; ; dir = filepath.Dir(dir) {
			cand := filepath.Join(dir, "node_modules", name)
			if real, err := filepath.EvalSymlinks(cand); err == nil {
				return real, true
			}
			if dir == root || dir == filepath.Dir(dir) {
				return "", false
			}
		}
	}

	top, err := read(root)
	if err != nil {
		return nil, fmt.Errorf("web/package.json: %w", err)
	}
	type pending struct {
		from, name string
		optional   bool
	}
	var queue []pending
	for _, n := range sortedKeys(top.Dependencies) {
		queue = append(queue, pending{root, n, false})
	}
	seen := map[string]bool{}
	var out []entry
	for len(queue) > 0 {
		q := queue[0]
		queue = queue[1:]
		dir, ok := resolve(q.from, q.name)
		if !ok {
			if q.optional {
				continue
			}
			return nil, fmt.Errorf("npm package %s (needed from %s) is not installed", q.name, q.from)
		}
		if seen[dir] {
			continue
		}
		seen[dir] = true
		p, err := read(dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", dir, err)
		}
		e, err := licensed(p.Name, p.Version, spdx(p.License), repoURL(p.Repository), dir)
		if err != nil {
			return nil, err
		}
		out = append(out, e)
		for _, n := range sortedKeys(p.Dependencies) {
			queue = append(queue, pending{dir, n, false})
		}
		for _, n := range sortedKeys(p.OptionalDependencies) {
			queue = append(queue, pending{dir, n, true})
		}
	}
	slices.SortFunc(out, func(a, b entry) int {
		if c := strings.Compare(a.name, b.name); c != 0 {
			return c
		}
		return strings.Compare(a.version, b.version)
	})
	return out, nil
}

func spdx(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var obj struct{ Type string }
	if json.Unmarshal(raw, &obj) == nil {
		return obj.Type
	}
	return ""
}

func repoURL(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) != nil {
		var obj struct{ URL string }
		if json.Unmarshal(raw, &obj) != nil {
			return ""
		}
		s = obj.URL
	}
	s = strings.TrimPrefix(s, "git+")
	s = strings.TrimSuffix(s, ".git")
	if after, ok := strings.CutPrefix(s, "git://"); ok {
		s = "https://" + after
	}
	if strings.HasPrefix(s, "github:") || !strings.Contains(s, ":") && strings.Count(s, "/") == 1 {
		s = "https://github.com/" + strings.TrimPrefix(s, "github:")
	}
	return s
}

var licenseName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents)(-[a-z0-9.-]+)?(\.(md|txt|rst))?$`)

// licensed reads the license files at the top of dir. An empty id is detected
// from the text.
func licensed(name, version, id, source, dir string) (entry, error) {
	e := entry{name: name, version: version, license: id, source: source}
	items, err := os.ReadDir(dir)
	if err != nil {
		return e, err
	}
	for _, it := range items {
		if it.IsDir() || !licenseName.MatchString(it.Name()) {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, it.Name()))
		if err != nil {
			return e, err
		}
		e.files = append(e.files, licenseFile{it.Name(), clean(string(raw))})
	}
	if len(e.files) == 0 {
		return e, fmt.Errorf("%s %s has no license file in %s", name, version, dir)
	}
	if e.license == "" {
		e.license = detect(e.files[0].text)
	}
	if e.license == "" {
		return e, fmt.Errorf("%s %s: license in %s not recognized; add it to detect()", name, version, e.files[0].name)
	}
	if !acceptedLicense(e.license) {
		return e, fmt.Errorf("%s %s declares license %q, which is not reviewed; add it to accepted after checking it", name, version, e.license)
	}
	return e, nil
}

// accepted are the licenses detect recognizes, which a declared license
// must also be.
var accepted = []string{"Apache-2.0", "MPL-2.0", "OFL-1.1", "MIT", "MIT-0", "ISC", "BSD-3-Clause", "BSD-2-Clause"}

// acceptedLicense reports whether id is an accepted license, or a choice
// (A OR B) offering one. Terms that add conditions (AND, WITH, nested
// parentheses) are not accepted.
func acceptedLicense(id string) bool {
	id = strings.TrimSuffix(strings.TrimPrefix(id, "("), ")")
	if strings.ContainsAny(id, "()") || strings.Contains(id, " AND ") || strings.Contains(id, " WITH ") {
		return false
	}
	for part := range strings.SplitSeq(id, " OR ") {
		if slices.Contains(accepted, strings.TrimSpace(part)) {
			return true
		}
	}
	return false
}

func clean(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t")
	}
	return strings.Trim(strings.Join(lines, "\n"), "\n")
}

// detect names the common licenses by their characteristic wording.
func detect(text string) string {
	t := strings.Join(strings.Fields(text), " ")
	has := func(s string) bool { return strings.Contains(t, s) }
	switch {
	case has("Apache License") && has("Version 2.0"):
		return "Apache-2.0"
	case has("Mozilla Public License Version 2.0"):
		return "MPL-2.0"
	case has("SIL OPEN FONT LICENSE Version 1.1"):
		return "OFL-1.1"
	case has("Permission is hereby granted, free of charge") && !has("shall be included in all copies"):
		return "MIT-0" // MIT without its attribution condition
	case has("Permission is hereby granted, free of charge"):
		return "MIT"
	case has("Permission to use, copy, modify, and/or distribute") || has("Permission to use, copy, modify, and distribute this software for any purpose with or without fee"):
		return "ISC"
	case has("Redistribution and use in source and binary forms") && (has("Neither the name") || has("may not be used to endorse")):
		return "BSD-3-Clause"
	case has("Redistribution and use in source and binary forms"):
		return "BSD-2-Clause"
	}
	return ""
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

// theme is an upstream color theme the files in web/src/styles/themes derive
// from. Palettes take colors, not code, from these projects; the notices
// credit them under their MIT licenses all the same.
type theme struct {
	name, source, copyright string
	files                   []string // theme file names without .css
}

